// Patch 0061 — 侧栏 Git 面板（P6 的"暂存/提交/拉取/推送 + worktree"入口）。
//
// 桌面端的 Git 是侧栏/状态栏里的一块；手机上是侧栏面板的一个标签（launcher 里多一项 Git）。
// 后端走 patches/0060 的 `/api/git`（app-server 没有 Git 方法，这部分是本项目自己实现的）。
//
// 交互取舍：
//   - 列表按「Staged / Changes / Untracked」分三段，每行给最少的必要动作（暂存 / 取消暂存 / 丢弃）；
//   - 丢弃、切换分支、push、删除 worktree 都要过确认弹层——手机上误触代价太高；
//   - 创建 worktree 之后问一句"要不要把工作区切过去"，这就是"会话关联"的落点：
//     新会话用当前工作区目录（与桌面端把项目指向 worktree 等价）；
//   - 危险动作之外不发确认（提交是本地且可回退的）。
//
// Usage: node patches/0061-git-panel.mjs [appDir]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const appDir = resolve(process.argv[2] ?? new URL("../app", import.meta.url).pathname);

function edit(file, marker, steps) {
  const path = resolve(appDir, file);
  let source = readFileSync(path, "utf8");
  if (source.includes(marker)) {
    console.log("skip  " + file + " (already applied)");
    return;
  }
  for (const [from, to, label] of steps) {
    const hits = source.split(from).length - 1;
    if (hits !== 1) throw new Error(file + ": cannot locate " + label + " exactly once (hits=" + hits + ")");
    source = source.replace(from, to);
    console.log("apply " + file + ": " + label);
  }
  writeFileSync(path, source);
}

